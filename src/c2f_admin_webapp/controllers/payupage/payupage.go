package payupage

import (
	"fmt"
	"html"
	"runtime/debug"

	"c2f_admin_webapp/model/util/log"

	"github.com/astaxie/beego"
)

// PayUPage serves an HTML auto-submit page that POSTs to PayU.
// Used by the iOS app (via SFSafariViewController / Browser.open) to bypass
// WKWebView detection — PayU blocks WKWebView but allows Safari/SFSafariViewController.
type PayUPage struct {
	beego.Controller
}

func (c *PayUPage) Get() {
	defer func() {
		if r := recover(); r != nil {
			stack := debug.Stack()
			log.Println(beego.AppConfig.String("loglevel"), "Exception", string(stack))
			c.Ctx.ResponseWriter.WriteHeader(500)
			c.Ctx.WriteString("Internal Server Error")
		}
	}()

	// Read and sanitize PayU params from query string.
	// The hash was already generated by C2FUserMobile's /GetPayUHash endpoint.
	key := html.EscapeString(c.GetString("key"))
	txnid := html.EscapeString(c.GetString("txnid"))
	amount := html.EscapeString(c.GetString("amount"))
	productinfo := html.EscapeString(c.GetString("productinfo"))
	firstname := html.EscapeString(c.GetString("firstname"))
	email := html.EscapeString(c.GetString("email"))
	phone := html.EscapeString(c.GetString("phone"))
	surl := html.EscapeString(c.GetString("surl"))
	furl := html.EscapeString(c.GetString("furl"))
	hash := html.EscapeString(c.GetString("hash"))

	payUURL := beego.AppConfig.String("PAYU_URL")
	if payUURL == "" {
		payUURL = "https://secure.payu.in/_payment"
	}

	htmlPage := fmt.Sprintf(`<!DOCTYPE html>
<html>
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Redirecting to payment...</title>
  <style>body{font-family:sans-serif;text-align:center;margin-top:60px;color:#555;}</style>
</head>
<body onload="document.getElementById('payuForm').submit()">
  <p>Redirecting to payment gateway, please wait...</p>
  <form id="payuForm" method="POST" action="%s">
    <input type="hidden" name="key"         value="%s">
    <input type="hidden" name="txnid"       value="%s">
    <input type="hidden" name="amount"      value="%s">
    <input type="hidden" name="productinfo" value="%s">
    <input type="hidden" name="firstname"   value="%s">
    <input type="hidden" name="email"       value="%s">
    <input type="hidden" name="phone"       value="%s">
    <input type="hidden" name="surl"        value="%s">
    <input type="hidden" name="furl"        value="%s">
    <input type="hidden" name="hash"        value="%s">
  </form>
</body>
</html>`,
		payUURL, key, txnid, amount, productinfo,
		firstname, email, phone, surl, furl, hash)

	c.Ctx.Output.Header("Content-Type", "text/html; charset=utf-8")
	c.Ctx.Output.Header("Cache-Control", "no-store, no-cache")
	c.Ctx.WriteString(htmlPage)
}
